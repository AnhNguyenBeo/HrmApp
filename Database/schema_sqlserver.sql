CREATE TABLE VaiTro (
    MaVaiTro UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    TenVaiTro NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(255) NULL,
    TinhTrangCan BIT NULL,
    CONSTRAINT PK_VaiTro PRIMARY KEY (MaVaiTro)
);
GO

CREATE TABLE PhongBan (
    MaPhongBan UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    TenPhongBan NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(255) NULL,
    CONSTRAINT PK_PhongBan PRIMARY KEY (MaPhongBan)
);
GO

CREATE TABLE ChucVu (
    MaChucVu UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    TenChucVu NVARCHAR(100) NOT NULL,
    PhuCapChucVu DECIMAL(18, 2) NOT NULL,
    CONSTRAINT PK_ChucVu PRIMARY KEY (MaChucVu)
);
GO

CREATE TABLE NhanVien (
    MaNhanVien UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATE NOT NULL,
    GioiTinh NVARCHAR(10) NOT NULL,
    CCCD VARCHAR(20) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    DiaChi NVARCHAR(255) NOT NULL,
    TrinhDoHocVan NVARCHAR(100) NOT NULL,
    MaPhongBan UNIQUEIDENTIFIER NOT NULL,
    MaChucVu UNIQUEIDENTIFIER NOT NULL,
    NgayVaoLam DATE NOT NULL,
    TrangThaiLamViec NVARCHAR(50) NOT NULL,
    NgayNghiViec DATE NULL,
    GhiChu NVARCHAR(MAX) NULL,
    CONSTRAINT PK_NhanVien PRIMARY KEY (MaNhanVien),
    CONSTRAINT UQ_NhanVien_CCCD UNIQUE (CCCD),
    CONSTRAINT UQ_NhanVien_Email UNIQUE (Email)
);
GO

CREATE TABLE TaiKhoan (
    MaTaiKhoan UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    MaNhanVien UNIQUEIDENTIFIER NOT NULL,
    TenDangNhap VARCHAR(50) NOT NULL,
    MatKhauHash VARCHAR(255) NOT NULL,
    MaVaiTro UNIQUEIDENTIFIER NOT NULL,
    TrangThai NVARCHAR(50) NOT NULL,
    NgayTao DATE NOT NULL,
    CONSTRAINT PK_TaiKhoan PRIMARY KEY (MaTaiKhoan),
    CONSTRAINT UQ_TaiKhoan_TenDangNhap UNIQUE (TenDangNhap)
);
GO

CREATE TABLE HopDongLaoDong (
    MaHopDong UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    MaNhanVien UNIQUEIDENTIFIER NOT NULL,
    LoaiHopDong NVARCHAR(100) NOT NULL,
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NULL,
    LuongCoBan DECIMAL(18, 2) NOT NULL,
    TrangThai NVARCHAR(50) NOT NULL,
    LuongThuong DECIMAL(18, 2) NULL,
    CONSTRAINT PK_HopDongLaoDong PRIMARY KEY (MaHopDong)
);
GO

CREATE TABLE ChamCong (
    MaChamCong UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    MaNhanVien UNIQUEIDENTIFIER NOT NULL,
    Ngay DATE NOT NULL,
    GioVao TIME NOT NULL,
    GioRa TIME NOT NULL,
    SoGioTangCa DECIMAL(4, 2) NULL,
    TrangThai NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_ChamCong PRIMARY KEY (MaChamCong),
    CONSTRAINT UQ_ChamCong_NhanVien_Ngay UNIQUE (MaNhanVien, Ngay)
);
GO

CREATE TABLE BangLuong (
    MaBangLuong UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    MaNhanVien UNIQUEIDENTIFIER NOT NULL,
    ThoiGian VARCHAR(10) NOT NULL,
    NgayCongChuan DECIMAL(4, 2) NOT NULL,
    SoNgayCong DECIMAL(4, 2) NOT NULL,
    TongGioOT DECIMAL(5, 2) NOT NULL,
    LuongCoBan DECIMAL(18, 2) NOT NULL,
    PhuCap DECIMAL(18, 2) NULL,
    TienThuong DECIMAL(18, 2) NULL,
    LuongOT DECIMAL(18, 2) NULL,
    BaoHiemXaHoi DECIMAL(18, 2) NULL,
    ThueTNCN DECIMAL(18, 2) NULL,
    ThucLinh DECIMAL(18, 2) NULL,
    TrangThaiChiTra NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_BangLuong PRIMARY KEY (MaBangLuong),
    CONSTRAINT UQ_BangLuong_NhanVien_ThoiGian UNIQUE (MaNhanVien, ThoiGian)
);
GO

CREATE TABLE DonTu (
    MaDon UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    MaNhanVien UNIQUEIDENTIFIER NOT NULL,
    HoTen NVARCHAR(100) NOT NULL,
    LoaiDon NVARCHAR(50) NOT NULL,
    LoaiNghi NVARCHAR(50) NULL,
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NOT NULL,
    SoNgayNghi DECIMAL(5, 2) NOT NULL,
    LyDo NVARCHAR(255) NOT NULL,
    TrangThai NVARCHAR(50) NOT NULL,
    NguoiDuyetMa UNIQUEIDENTIFIER NULL,
    NgayDuyet DATE NULL,
    GhiChuDuyet NVARCHAR(MAX) NULL,
    CONSTRAINT PK_DonTu PRIMARY KEY (MaDon)
);
GO

CREATE TABLE NhatKyHoatDong (
    MaLog UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),
    ThoiGian DATETIME NOT NULL DEFAULT GETDATE(),
    TenDangNhap NVARCHAR(100) NOT NULL,
    HoTen NVARCHAR(150) NULL,
    HanhDong NVARCHAR(100) NOT NULL,
    ChiTiet NVARCHAR(MAX) NULL,
    TrangThai NVARCHAR(50) NOT NULL DEFAULT N'Thành công',
    DiaChiIP NVARCHAR(50) NULL,
    CONSTRAINT PK_NhatKyHoatDong PRIMARY KEY (MaLog)
);
GO

